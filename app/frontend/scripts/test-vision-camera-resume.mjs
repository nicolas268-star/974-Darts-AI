import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source = readFileSync(new URL('../app/admin/vision/VisionLab.tsx', import.meta.url), 'utf8');
const ast = ts.createSourceFile('VisionLab.tsx', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
const component = ast.statements.find(n => ts.isFunctionDeclaration(n) && n.name?.text === 'VisionLab');
const start = component.body.statements.find(n => ts.isFunctionDeclaration(n) && n.name?.text === 'startCamera');
const code = ts.transpileModule(start.getText(ast) + '\nmodule.exports = startCamera;', { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
async function run(resume, { width = 720, height = 1280, fail = false, stale = false } = {}) {
  const before = { sourceWidth: 720, sourceHeight: 1280 };
  const state = { before, calibration: { retained: true }, after: { retained: true }, verified: true, samples: [{ truth: 'S1' }] };
  let constraints, stops = 0;
  const sandbox = { module: { exports: {} }, journalLock: { current: false }, source: 'camera', before, calibration: state.calibration, cameraDevice: { current: 'rear-camera' }, generation: { current: 0 }, mounted: { current: true }, window: { isSecureContext: true }, document: { visibilityState: 'visible' }, streamRef: { current: null }, wakeRef: { current: null }, errorMessage: e => e.message };
  sandbox.stop = () => { sandbox.generation.current++; state.camera = false; state.starting = false; state.resumeCheck = true; sandbox.streamRef.current?.getTracks().forEach(t => t.stop()); sandbox.streamRef.current = null; };
  const track = { stop: () => stops++, getSettings: () => ({ deviceId: 'rear-camera' }), addEventListener: () => {} };
  sandbox.navigator = { mediaDevices: { getUserMedia: async c => { constraints = c; if (fail) throw Error('Permission refusée'); if (stale) sandbox.generation.current++; return { getTracks: () => [track], getVideoTracks: () => [track] }; } } };
  sandbox.videoRef = { current: { videoWidth: width, videoHeight: height, play: async () => {} } };
  for (const name of code.matchAll(/\b(set[A-Z]\w*)\(/g)) {
    const key = name[1].slice(3); sandbox[name[1]] = value => { state[key[0].toLowerCase() + key.slice(1)] = value; };
  }
  vm.runInNewContext(code, sandbox);
  await sandbox.module.exports(resume);
  return { state, constraints, stops, before };
}
let r = await run(true);
assert.equal(r.state.before, r.before);
assert.equal(r.state.calibration.retained, true);
assert.equal(r.state.after.retained, true);
assert.equal(r.state.samples[0].truth, 'S1');
assert.equal(r.state.camera, true);
assert.equal(r.state.resumeCheck, true);
assert.equal(r.constraints.video.deviceId.exact, 'rear-camera');
assert.equal(r.state.watching, undefined, 'resume must not arm detection');
r = await run(false);
assert.equal(r.state.before, null);
assert.equal(r.state.calibration, null);
assert.equal(r.state.after, null);
assert.equal(r.state.resumeCheck, false);
assert.equal(r.constraints.video.deviceId, undefined);
r = await run(true, { width: 1280, height: 720 });
assert.equal(r.state.camera, false);
assert.equal(r.state.verified, false);
assert.equal(r.state.before, r.before);
assert.equal(r.state.after.retained, true);
assert.equal(r.stops, 1);
r = await run(true, { fail: true });
assert.equal(r.state.camera, false);
assert.equal(r.state.before, r.before);
assert.equal(r.state.calibration.retained, true);
assert.match(r.state.message, /Permission refusée/);
r = await run(true, { stale: true });
assert.equal(r.state.camera, false);
assert.equal(r.stops, 1);
console.log('PASS camera resume: preserved session, explicit restart, format change, permission denial, stale request; no automatic arming.');
const arm = component.body.statements.find(n => ts.isFunctionDeclaration(n) && n.name?.text === 'arm');
const armCode = ts.transpileModule(arm.getText(ast) + '\nmodule.exports = arm;', { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
const guard = { module: { exports: {} }, before: {}, calibration: {}, verified: true, camera: true, resumeCheck: true, after: null, pause: () => assert.fail('Detection must remain blocked until framing is confirmed') };
vm.runInNewContext(armCode, guard);
guard.module.exports();
guard.module.exports(true);
console.log('PASS camera resume: automatic and manual capture blocked before framing confirmation.');
